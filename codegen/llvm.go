package codegen

import (
	"ezsharp/parser"
	"fmt"
	"strings"
)

func LLVMCodegen(symbolTable []parser.Parse) (string, error) {
	var output strings.Builder
	output.WriteString(`; Generated by GoSharp

@fmt = private constant [4 x i8] c"%d\0A\00"
declare i32 @printf(ptr, ...)

define i32 @main() {
entry:
`)

	var tempCount, loopCount int
	var activeLoops []int
	for i := 0; i < len(symbolTable); {
		symbol := symbolTable[i]
		i++

		switch symbol.Token {
		case "VAR_DECLARE":
			if symbol.Type != "INT" {
				return "", fmt.Errorf("line %d: unsupported variable type %s", symbol.Line, symbol.Type)
			}
			fmt.Fprintf(&output, "  %%%s.addr = alloca i32\n", symbol.Literal)
		case "VAR_ASSIGN", "STATEMENT":
			if symbol.Token == "STATEMENT" && symbol.Literal != "print" {
				return "", fmt.Errorf("line %d: unsupported statement %q", symbol.Line, symbol.Literal)
			}
			value, err := emitIntExpr(symbolTable, &i, 1, &output, &tempCount)
			if err != nil {
				return "", fmt.Errorf("line %d: %w", symbol.Line, err)
			}
			if symbol.Token == "VAR_ASSIGN" {
				fmt.Fprintf(&output, "  store i32 %s, ptr %%%s.addr\n", value, symbol.Literal)
			} else {
				fmt.Fprintf(&output, "  call i32 (ptr, ...) @printf(ptr @fmt, i32 %s)\n", value)
			}
		case "WHILE":
			loop := loopCount
			loopCount++
			fmt.Fprintf(&output, "  br label %%while.cond.%d\n\nwhile.cond.%d:\n", loop, loop)
			condition, err := emitIntComparison(symbolTable, &i, &output, &tempCount)
			if err != nil {
				return "", fmt.Errorf("line %d: %w", symbol.Line, err)
			}
			if i == len(symbolTable) || symbolTable[i].Token != "DO" {
				return "", fmt.Errorf("line %d: expected do after while condition", symbol.Line)
			}
			i++
			fmt.Fprintf(&output, "  br i1 %s, label %%while.body.%d, label %%while.end.%d\n\nwhile.body.%d:\n",
				condition, loop, loop, loop)
			activeLoops = append(activeLoops, loop)
		case "OD":
			if len(activeLoops) == 0 {
				return "", fmt.Errorf("line %d: od without while", symbol.Line)
			}
			loop := activeLoops[len(activeLoops)-1]
			activeLoops = activeLoops[:len(activeLoops)-1]
			fmt.Fprintf(&output, "  br label %%while.cond.%d\n\nwhile.end.%d:\n", loop, loop)
		case "EOF":
		default:
			return "", fmt.Errorf("line %d: unsupported LLVM record %s (%q)", symbol.Line, symbol.Token, symbol.Literal)
		}
	}
	if len(activeLoops) != 0 {
		return "", fmt.Errorf("expected od to close while loop")
	}

	output.WriteString("  ret i32 0\n}\n")
	return output.String(), nil
}

// Consume an operand and any arithmetic operators that bind at this precedence.
func emitIntExpr(
	records []parser.Parse, index *int, minPrecedence int, output *strings.Builder, tempCount *int,
) (string, error) {
	if *index >= len(records) {
		return "", fmt.Errorf("expected an integer operand")
	}
	left, err := emitIntOperand(records[*index], output, tempCount)
	if err != nil {
		return "", err
	}
	(*index)++

	for *index < len(records) && records[*index].Token == "OPERATOR" {
		operator := records[*index].Literal
		precedence := priority(operator)
		if precedence < minPrecedence {
			break
		}
		(*index)++

		right, err := emitIntExpr(records, index, precedence+1, output, tempCount)
		if err != nil {
			return "", err
		}
		left, err = emitOperator(operator, left, right, output, tempCount)
		if err != nil {
			return "", err
		}
	}
	return left, nil
}

func emitIntComparison(records []parser.Parse, index *int, output *strings.Builder, tempCount *int) (string, error) {
	left, err := emitIntExpr(records, index, 1, output, tempCount)
	if err != nil {
		return "", err
	}
	if *index >= len(records) || records[*index].Token != "RELOP" {
		return "", fmt.Errorf("expected an integer comparison")
	}
	operator := records[*index].Literal
	var predicate string
	switch operator {
	case "<":
		predicate = "slt"
	case "<=":
		predicate = "sle"
	case ">":
		predicate = "sgt"
	case ">=":
		predicate = "sge"
	case "==":
		predicate = "eq"
	case "<>":
		predicate = "ne"
	default:
		return "", fmt.Errorf("unsupported comparison %q", operator)
	}
	(*index)++
	right, err := emitIntExpr(records, index, 1, output, tempCount)
	if err != nil {
		return "", err
	}

	tempName := fmt.Sprintf("%%tmp.%d", *tempCount)
	(*tempCount)++
	fmt.Fprintf(output, "  %s = icmp %s i32 %s, %s\n", tempName, predicate, left, right)
	return tempName, nil
}

func emitIntOperand(symbol parser.Parse, output *strings.Builder, tempCount *int) (string, error) {
	if symbol.Type != "INT" {
		return "", fmt.Errorf("expected an integer operand, got %q", symbol.Literal)
	}

	switch symbol.Token {
	case "LITERAL":
		return symbol.Literal, nil
	case "VAR_REFERENCE":
		tempName := fmt.Sprintf("%%%s.value.%d", symbol.Literal, *tempCount)
		(*tempCount)++
		fmt.Fprintf(output, "  %s = load i32, ptr %%%s.addr\n", tempName, symbol.Literal)
		return tempName, nil
	default:
		return "", fmt.Errorf("unsupported operand %q (%s)", symbol.Literal, symbol.Token)
	}
}

func emitOperator(operator, left, right string, output *strings.Builder, tempCount *int) (string, error) {
	var opcode string
	switch operator {
	case "+":
		opcode = "add"
	case "-":
		opcode = "sub"
	case "*":
		opcode = "mul"
	case "/":
		opcode = "sdiv"
	case "%":
		opcode = "srem"
	default:
		return "", fmt.Errorf("unsupported operator %q", operator)
	}

	tempName := fmt.Sprintf("%%tmp.%d", *tempCount)
	(*tempCount)++
	fmt.Fprintf(output, "  %s = %s i32 %s, %s\n", tempName, opcode, left, right)
	return tempName, nil
}
